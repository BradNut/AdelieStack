#!/usr/bin/env node
/**
 * Opt-in TanStack Query setup for apps/web.
 *
 *   pnpm setup:query              install (idempotent: a second run is a no-op)
 *   pnpm setup:query --uninstall  remove everything this script added, including the dependency
 *
 * What it manages:
 *   - the `@tanstack/svelte-query` dependency in apps/web
 *   - a marker-delimited QueryClientProvider edit in the web root layout
 *   - `$lib/query/` (QueryClient factory, API error type, typed query-option factories)
 *   - two example routes: SSR prefetch + hydration, and an SSR-only (no Query) fallback
 *
 * Safety: every edit is computed and verified (including an exact install -> uninstall round trip of
 * the root layout) before anything is written. If a step fails, completed steps are rolled back and
 * the script exits non-zero. Uninstall refuses to delete generated files you have modified unless
 * `--force` is passed.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEB_DIR = path.join(ROOT_DIR, 'apps', 'web');
const WEB_PACKAGE_NAME = '@adelie/web';
const WEB_PACKAGE_JSON = path.join(WEB_DIR, 'package.json');
const LOCKFILE = path.join(ROOT_DIR, 'pnpm-lock.yaml');
const ROOT_LAYOUT = path.join(WEB_DIR, 'src', 'routes', '+layout.svelte');

const DEPENDENCY_NAME = '@tanstack/svelte-query';
const DEPENDENCY_RANGE = '^6.2.4';

const LOG_PREFIX = '[setup:query]';
const MARKER = 'setup:query';

const FLAGS = {
	uninstall: '--uninstall',
	force: '--force',
	help: '--help',
};

