/** Directories the script may create; removed on uninstall only when empty. Deepest first. */
const GENERATED_DIRS = [PREFETCH_EXAMPLE_DIR, SSR_ONLY_EXAMPLE_DIR, EXAMPLES_DIR, QUERY_LIB_DIR];

/* -------------------------------------------------------------------------- */
/*                              Root layout edit                              */
/* -------------------------------------------------------------------------- */

const INDENT = '\t';

const LAYOUT_SCRIPT_BLOCK = [
	`${INDENT}// ${MARKER}:start - managed by \`pnpm setup:query\`; remove with \`pnpm setup:query --uninstall\``,
	`${INDENT}import { QueryClientProvider } from "@tanstack/svelte-query";`,
	`${INDENT}import { createAppQueryClient } from "$lib/query";`,
	'',
	`${INDENT}const queryClient = createAppQueryClient();`,
	`${INDENT}// ${MARKER}:end`,
	'',
].join('\n');

/** Opening instance `<script>` tag on its own line (module scripts are excluded). */
const SCRIPT_OPEN_PATTERN = /^<script(?![^>]*\bmodule\b)[^>]*>\n/gm;
/** The single children render tag the provider wraps. */
const CHILDREN_RENDER_PATTERN = /^([ \t]*)(\{@render children(?:\?\.)?\(\)\})[ \t]*$/gm;
/** The exact shape `wrapChildren` produces. */
const WRAPPED_CHILDREN_PATTERN = new RegExp(
	[
		`^([ \\t]*)<!-- ${MARKER}:start -->`,
		'\\1<QueryClientProvider client=\\{queryClient\\}>',
		`\\1${INDENT}(\\{@render children(?:\\?\\.)?\\(\\)\\})`,
		'\\1</QueryClientProvider>',
		`\\1<!-- ${MARKER}:end -->$`,
	].join('\n'),
	'gm',
);

function wrapChildren(indent, renderTag) {
	return [
		`${indent}<!-- ${MARKER}:start -->`,
		`${indent}<QueryClientProvider client={queryClient}>`,
		`${indent}${INDENT}${renderTag}`,
		`${indent}</QueryClientProvider>`,
		`${indent}<!-- ${MARKER}:end -->`,
	].join('\n');
}

function countMatches(source, pattern) {
	return [...source.matchAll(pattern)].length;
}

function patchLayout(source) {
	const relative = path.relative(ROOT_DIR, ROOT_LAYOUT);
	if (source.includes('\r\n')) {
		throw new SetupError(`${relative} uses CRLF line endings; convert it to LF before running this script.`);
	}
	if (source.includes(MARKER)) {
		throw new SetupError(`${relative} already contains "${MARKER}" markers.`);
	}
	if (source.includes('QueryClientProvider')) {
		throw new SetupError(`${relative} already references QueryClientProvider; refusing to add a second provider.`);
	}
	const scriptTags = countMatches(source, SCRIPT_OPEN_PATTERN);
	if (scriptTags !== 1) {
		throw new SetupError(`${relative}: expected exactly one instance <script> tag on its own line, found ${scriptTags}.`);
	}
	const renderTags = countMatches(source, CHILDREN_RENDER_PATTERN);
	if (renderTags !== 1) {
		throw new SetupError(`${relative}: expected exactly one "{@render children()}" line to wrap, found ${renderTags}.`);
	}

	const patched = source
		.replace(SCRIPT_OPEN_PATTERN, (openTag) => `${openTag}${LAYOUT_SCRIPT_BLOCK}`)
		.replace(CHILDREN_RENDER_PATTERN, (_match, indent, renderTag) => wrapChildren(indent, renderTag));

	// Only apply an edit we can prove we can undo byte for byte.
	if (unpatchLayout(patched) !== source) {
		throw new SetupError(`${relative}: the layout edit would not be cleanly reversible; aborting.`);
	}
	return patched;
}

function unpatchLayout(source) {
	const relative = path.relative(ROOT_DIR, ROOT_LAYOUT);
	const scriptBlocks = source.split(LAYOUT_SCRIPT_BLOCK).length - 1;
	const wrappedBlocks = countMatches(source, WRAPPED_CHILDREN_PATTERN);
	if (scriptBlocks !== 1 || wrappedBlocks !== 1) {
		throw new SetupError(
			`${relative}: the "${MARKER}" blocks were modified (script block found ${scriptBlocks}x, provider block found ${wrappedBlocks}x). ` +
				'Remove them by hand or restore the generated text, then rerun.',
		);
	}
	const restored = source.replace(LAYOUT_SCRIPT_BLOCK, '').replace(WRAPPED_CHILDREN_PATTERN, (_match, indent, renderTag) => `${indent}${renderTag}`);
	if (restored.includes(MARKER)) {
		throw new SetupError(`${relative}: stray "${MARKER}" markers remain after removing the managed blocks.`);
	}
	return restored;
}

/* -------------------------------------------------------------------------- */
/*                                   Helpers                                  */
/* -------------------------------------------------------------------------- */

class SetupError extends Error {}

function log(message) {
	console.log(`${LOG_PREFIX} ${message}`);
}

function webPath(relativePath) {
	return path.join(WEB_DIR, relativePath);
}

function readWebPackage() {
	return JSON.parse(readFileSync(WEB_PACKAGE_JSON, 'utf8'));
}

function hasDependency() {
	const pkg = readWebPackage();
	return Boolean(pkg.dependencies?.[DEPENDENCY_NAME] ?? pkg.devDependencies?.[DEPENDENCY_NAME]);
}

function readOptional(filePath) {
	return existsSync(filePath) ? readFileSync(filePath, 'utf8') : null;
}

function runPnpm(args) {
	log(`pnpm ${args.join(' ')}`);
	const result = spawnSync('pnpm', args, { cwd: ROOT_DIR, stdio: 'inherit' });
	if (result.error) {
		throw new SetupError(`could not run pnpm: ${result.error.message}`);
	}
	if (result.status !== 0) {
		throw new SetupError(`pnpm ${args.join(' ')} exited with status ${result.status}.`);
	}
}

function inspect() {
	const layout = readFileSync(ROOT_LAYOUT, 'utf8');
	const files = Object.entries(GENERATED_FILES).map(([relativePath, expected]) => {
		const actual = readOptional(webPath(relativePath));
		return { relativePath, exists: actual !== null, modified: actual !== null && actual !== expected };
	});
	return {
		layout,
		dependency: hasDependency(),
		layoutPatched: layout.includes(MARKER),
		files,
		existingFiles: files.filter((file) => file.exists),
	};
}

function describeParts(state) {
	return [
		state.dependency && `dependency ${DEPENDENCY_NAME}`,
		state.layoutPatched && 'root layout provider',
		...state.existingFiles.map((file) => file.relativePath),
	].filter(Boolean);
}

function removeEmptyGeneratedDirs() {
	for (const dir of GENERATED_DIRS) {
		const absolute = webPath(dir);
		if (existsSync(absolute) && readdirSync(absolute).length === 0) {
			rmdirSync(absolute);
		}
	}
}

/* -------------------------------------------------------------------------- */
/*                                  Commands                                  */
/* -------------------------------------------------------------------------- */

function install() {
	const state = inspect();
	const present = describeParts(state);
	const total = Object.keys(GENERATED_FILES).length + 2;

	if (present.length === total) {
		log('TanStack Query is already set up; nothing to do.');
		return;
	}
	if (present.length > 0) {
		throw new SetupError(
			`found a partial setup (${present.join(', ')}). Run \`pnpm setup:query --uninstall\` first, then rerun \`pnpm setup:query\`.`,
		);
	}

	// Preflight: compute every edit before touching the tree.
	const patchedLayout = patchLayout(state.layout);
	const packageSnapshot = readFileSync(WEB_PACKAGE_JSON, 'utf8');
	const lockSnapshot = readOptional(LOCKFILE);

	const createdFiles = [];
	let layoutWritten = false;
	try {
		for (const [relativePath, content] of Object.entries(GENERATED_FILES)) {
			const absolute = webPath(relativePath);
			mkdirSync(path.dirname(absolute), { recursive: true });
			writeFileSync(absolute, content, { flag: 'wx' });
			createdFiles.push(absolute);
		}
		log(`wrote ${createdFiles.length} files under apps/web`);

		writeFileSync(ROOT_LAYOUT, patchedLayout);
		layoutWritten = true;
		log('added QueryClientProvider to apps/web/src/routes/+layout.svelte');

		runPnpm(['--filter', WEB_PACKAGE_NAME, 'add', `${DEPENDENCY_NAME}@${DEPENDENCY_RANGE}`]);
	} catch (error) {
		console.error(`${LOG_PREFIX} install failed; rolling back.`);
		for (const file of createdFiles) {
			rmSync(file, { force: true });
		}
		removeEmptyGeneratedDirs();
		if (layoutWritten) {
			writeFileSync(ROOT_LAYOUT, state.layout);
		}
		if (readFileSync(WEB_PACKAGE_JSON, 'utf8') !== packageSnapshot) {
			writeFileSync(WEB_PACKAGE_JSON, packageSnapshot);
		}
		if (lockSnapshot !== null && readFileSync(LOCKFILE, 'utf8') !== lockSnapshot) {
			writeFileSync(LOCKFILE, lockSnapshot);
		}
		throw error;
	}

	log('done. Try /examples/query-prefetch and /examples/ssr-only. Undo with `pnpm setup:query --uninstall`.');
}

function uninstall({ force }) {
	const state = inspect();
	const present = describeParts(state);

	if (present.length === 0) {
		log('TanStack Query is not set up; nothing to remove.');
		return;
	}

	// Preflight: fail before changing anything.
	const restoredLayout = state.layoutPatched ? unpatchLayout(state.layout) : null;
	const modified = state.files.filter((file) => file.modified);
	if (modified.length > 0 && !force) {
		throw new SetupError(
			`these generated files were modified: ${modified.map((file) => file.relativePath).join(', ')}. ` +
				`Rerun with ${FLAGS.force} to delete them anyway.`,
		);
	}

	// The dependency goes first: it is the step most likely to fail, and nothing else has changed yet.
	if (state.dependency) {
		runPnpm(['--filter', WEB_PACKAGE_NAME, 'remove', DEPENDENCY_NAME]);
	}
	if (restoredLayout !== null) {
		writeFileSync(ROOT_LAYOUT, restoredLayout);
		log('removed QueryClientProvider from apps/web/src/routes/+layout.svelte');
	}
	for (const file of state.existingFiles) {
		rmSync(webPath(file.relativePath));
	}
	removeEmptyGeneratedDirs();
	log(`removed ${state.existingFiles.length} generated files. TanStack Query is uninstalled.`);
}

function printHelp() {
	console.log(`Usage: pnpm setup:query [${FLAGS.uninstall} [${FLAGS.force}]]

Installs an opt-in TanStack Query setup into apps/web, or removes it with ${FLAGS.uninstall}.
${FLAGS.force}  with ${FLAGS.uninstall}, delete generated files even if you modified them.`);
}

function main(argv) {
	const known = new Set(Object.values(FLAGS));
	// \`pnpm setup:query -- --uninstall\` forwards the separator; ignore it.
	const args = argv.filter((arg) => arg !== '--');
	const unknown = args.filter((arg) => !known.has(arg));
	if (unknown.length > 0) {
		throw new SetupError(`unknown argument(s): ${unknown.join(' ')}. See ${FLAGS.help}.`);
	}
	if (args.includes(FLAGS.help)) {
		printHelp();
		return;
	}
	if (args.includes(FLAGS.force) && !args.includes(FLAGS.uninstall)) {
		throw new SetupError(`${FLAGS.force} only applies to ${FLAGS.uninstall}.`);
	}
	if (args.includes(FLAGS.uninstall)) {
		uninstall({ force: args.includes(FLAGS.force) });
		return;
	}
	install();
}

try {
	main(process.argv.slice(2));
} catch (error) {
	const message = error instanceof Error ? error.message : String(error);
	console.error(`${LOG_PREFIX} error: ${message}`);
	process.exitCode = 1;
}
